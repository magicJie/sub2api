package service

import (
	"net"
	"net/url"
	"strconv"
	"time"
)

const (
	FallbackModeNone   = "none"
	FallbackModeProxy  = "proxy"
	FallbackModeDirect = "direct"
)

type Proxy struct {
	ID             int64
	Name           string
	Protocol       string
	Host           string
	Port           int
	Username       string
	Password       string
	Status         string
	CreatedAt      time.Time
	UpdatedAt      time.Time
	ExpiresAt      *time.Time
	FallbackMode   string
	BackupProxyID  *int64
	ExpiryWarnDays int

	// 链式代理（fork）：前置代理与 ss/vmess/vless/trojan 协议参数，见 proxy_chain.go。
	UpstreamMode       string
	UpstreamProxyID    *int64
	UpstreamHopGroupID *int64
	Options            map[string]string

	PoolID  *int64 // 代理池（fork）：所属代理池，nil 为默认池，见 proxy_pool.go。
	Role    string // 代理池（fork）：egress | transport，transport 不进代理池、不绑账号，见 proxy_pool.go。
}

func (p *Proxy) IsActive() bool {
	return p.Status == StatusActive
}

// IsExpired 报告代理是否已过期（基于 expires_at，与 status 无关）。
func (p *Proxy) IsExpired(now time.Time) bool {
	return p.ExpiresAt != nil && !p.ExpiresAt.After(now)
}

func (p *Proxy) URL() string {
	if chainURL, ok := proxyChainURL(p); ok { // 链式代理（fork）
		return chainURL
	}
	u := &url.URL{
		Scheme: p.Protocol,
		Host:   net.JoinHostPort(p.Host, strconv.Itoa(p.Port)),
	}
	if p.Username != "" && p.Password != "" {
		u.User = url.UserPassword(p.Username, p.Password)
	}
	return u.String()
}


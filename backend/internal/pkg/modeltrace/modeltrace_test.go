func TestParseNumbers(t *testing.T) {
	for _, test := range []struct {
		name string
		text string
		want []int
	}{
		{"longest run", "There are 300 values: 1, 2, 355. done 4 5", []int{1, 2, 355}},
		{"unicode letters separate", "1,2 中文 3,4,5", []int{3, 4, 5}},
		{"first tied run", "1,2 next 3,4", []int{1, 2}},
		{"out of range and punctuation", "0;1 / 356 / 355 / 9999999999999999999999999999 / 2", []int{1, 355, 2}},
		{"refusal", "I cannot generate these values.", []int{}},
		{"range alone", "1 to 355", []int{1}},
	} {
		t.Run(test.name, func(t *testing.T) {
			if got := parseNumbers(test.text); !reflect.DeepEqual(got, test.want) {
				t.Fatalf("parseNumbers() = %v, want %v", got, test.want)
			}
		})
	}
}

func TestAnalyzeAcceptance(t *testing.T) {
	for _, test := range []struct {
		count    int
		expected int
		minimum  int
		accepted bool
	}{
		{79, 0, 80, false},
		{80, 0, 80, true},
		{164, 300, 165, false},
		{165, 300, 165, true},
		{165, 301, 166, false},
		{166, 301, 166, true},
	} {
		t.Run(fmt.Sprintf("%d-of-%d", test.count, test.expected), func(t *testing.T) {
			result, err := Analyze([]Output{{Text: strings.Repeat("17,", test.count), ExpectedCount: test.expected}})
			if test.accepted && err != nil {
				t.Fatal(err)
			}
			if !test.accepted && !errors.Is(err, ErrNoUsableOutputs) {
				t.Fatalf("error = %v, want ErrNoUsableOutputs", err)
			}
			if len(result.Diagnostics) != 1 || result.Diagnostics[0].MinimumNumbers != test.minimum || result.Diagnostics[0].Accepted != test.accepted || result.Diagnostics[0].ParsedNumbers != test.count {
				t.Fatalf("unexpected diagnostics: %+v", result.Diagnostics)
			}
		})
	}
	result, err := Analyze([]Output{{Text: "I cannot complete this task. 1 through 355", ExpectedCount: 300}})
	if !errors.Is(err, ErrNoUsableOutputs) || result.UsedOutputs != 0 {
		t.Fatalf("refusal: result=%+v error=%v", result, err)
	}
	if _, err := Analyze(nil); !errors.Is(err, ErrNoUsableOutputs) {
		t.Fatalf("empty input: error=%v", err)
	}
}

func TestProjectionUsesOriginalVector(t *testing.T) {
	// Nonorthogonal directions distinguish simultaneous matrix projection from
	// the sequential subtraction in upstream's JavaScript implementation.
	original := []float64{2, 3}
	basis := [][]float64{{1, 0}, {0.5, 0.5}}
	output := make([]float64, len(original))
	subtractBasis(original, basis, output)
	if !reflect.DeepEqual(output, []float64{-1.25, 1.75}) {
		t.Fatalf("projected = %v", output)
	}
	if !reflect.DeepEqual(original, []float64{2, 3}) {
		t.Fatalf("original vector mutated: %v", original)
	}
}

func TestOrderedFeatureUnevenBlocks(t *testing.T) {
	var feature [orderedDimension]float64
	orderedFeature([]int{1, 23, 24, 90, 178, 267, 355, 1, 355}, feature[:])
	// numpy.array_split assigns the remainder to the first blocks: 3,2,2,2.
	for _, test := range []struct {
		index int
		want  float64
	}{
		{0, math.Sqrt(2.5 / 11)},
		{1, math.Sqrt(1.5 / 11)},
		{2, math.Sqrt(0.5 / 11)},
		{16 + 4, math.Sqrt(1.5 / 10)},
		{16 + 7, math.Sqrt(1.5 / 10)},
		{32 + 11, math.Sqrt(1.5 / 10)},
		{32 + 15, math.Sqrt(1.5 / 10)},
		{48, math.Sqrt(1.5 / 10)},
		{48 + 15, math.Sqrt(1.5 / 10)},
		{64 + 1, math.Sqrt(2.5 / 14)},
		{64 + 5, math.Sqrt(2.5 / 14)},
	} {
		if math.Abs(feature[test.index]-test.want) > 1e-14 {
			t.Errorf("feature[%d] = %.17g, want %.17g", test.index, feature[test.index], test.want)
		}
	}
	for block := range 4 {
		if got := dot(feature[block*16:(block+1)*16], feature[block*16:(block+1)*16]); math.Abs(got-1) > 1e-14 {
			t.Errorf("block %d squared norm = %g", block, got)
		}
	}
	if got := dot(feature[64:], feature[64:]); math.Abs(got-1) > 1e-14 {
		t.Errorf("last digit squared norm = %g", got)
	}
}


func TestGenerateChallenges(t *testing.T) {
	challenges := GenerateChallenges()
	if len(challenges) != 3 {
		t.Fatalf("got %d challenges", len(challenges))
	}
	seen := make(map[string]bool)
	for _, challenge := range challenges {
		if challenge.ExpectedCount < 292 || challenge.ExpectedCount > 332 || seen[challenge.Prompt] {
			t.Fatalf("invalid challenge: %+v", challenge)
		}
		seen[challenge.Prompt] = true
		for _, required := range []string{fmt.Sprint(challenge.ExpectedCount), "1 到 355", "禁止调用", "每个位置都要单独选择", "不要连续递增或递减"} {
			if !strings.Contains(challenge.Prompt, required) {
				t.Errorf("challenge missing %q", required)
			}
		}
	}
}
